export interface Glyph {
  /** Ink columns used (the advance is always CELL). */
  readonly w: number
  /** Rows of '#'/'.' from the top of the cell. */
  readonly rows: readonly string[]
}

const glyphs = new Map<string, Glyph>()
for (const [ch, rows] of Object.entries(G)) {
  glyphs.set(ch, { w: Math.max(0, ...rows.map((r) => r.length)), rows })
}

export function hasGlyph(ch: string): boolean {
  return glyphs.has(ch)
}

/** The glyph for a character; unknown characters draw as '?'. */
export function glyph(ch: string): Glyph {
  return glyphs.get(ch) ?? glyphs.get('?')!
}

/** All characters the font can draw. */
export function fontChars(): string[] {
  return [...glyphs.keys()]
}

/** Pixel width of a string: every character is one cell. */
export function measure(text: string): number {
  return [...text].length * CELL
}

/** Characters in a string (so ℓ and friends count as one). */
export function length(text: string): number {
  return [...text].length
}

/**
 * Breaks text into lines of at most `cols` characters, at spaces where it
 * can. '\n' forces a break. A word longer than a line is split.
 */
export function wrap(text: string, cols: number): string[] {
  const out: string[] = []
  for (const para of text.split('\n')) {
    const words = para.split(' ')
    let line = ''
    for (const raw of words) {
      let word = raw
      while (length(word) > cols) {
        if (line) {
          out.push(line)
          line = ''
        }
        const chars = [...word]
        out.push(chars.slice(0, cols).join(''))
        word = chars.slice(cols).join('')
      }
      if (!line) line = word
      else if (length(line) + 1 + length(word) <= cols) line += ' ' + word
      else {
        out.push(line)
        line = word
      }
    }
    out.push(line)
  }
  return out
}

/** Right-pads (or truncates) to exactly n characters, for menus laid out in columns. */
export function pad(text: string, n: number): string {
  const chars = [...text]
  return chars.length >= n ? chars.slice(0, n).join('') : text + ' '.repeat(n - chars.length)
}

/** Left-pads a number or string to n characters. */
export function padStart(text: string | number, n: number, fill = ' '): string {
  const s = String(text)
  return length(s) >= n ? s : fill.repeat(n - length(s)) + s
}
