/** Every glyph as a bitmap: width and the set pixels. */
export interface Glyph {
  w: number
  rows: readonly string[]
}

const GLYPHS = new Map<string, Glyph>()
for (const [ch, rows] of Object.entries(G)) GLYPHS.set(ch, { w: rows[0].length, rows })

/** Characters the font can draw. Anything else is drawn as '?'. */
export function glyph(ch: string): Glyph {
  return GLYPHS.get(ch) ?? GLYPHS.get('?')!
}

export function hasGlyph(ch: string): boolean {
  return GLYPHS.has(ch)
}

export function charAdvance(ch: string): number {
  return glyph(ch).w + TRACKING
}

/** Width in pixels of a line of text (no trailing tracking). */
export function measure(text: string): number {
  let w = 0
  for (const ch of text) w += charAdvance(ch)
  return Math.max(0, w - TRACKING)
}

/**
 * Word-wraps `text` into lines no wider than `width`. Explicit '\n' always
 * breaks. A single word longer than the line is split where it must.
 */
export function wrap(text: string, width: number): string[] {
  const out: string[] = []
  for (const para of text.split('\n')) {
    let line = ''
    for (const word of para.split(' ')) {
      const candidate = line ? `${line} ${word}` : word
      if (measure(candidate) <= width) {
        line = candidate
        continue
      }
      if (line) out.push(line)
      line = word
      while (measure(line) > width) {
        let cut = line.length - 1
        while (cut > 1 && measure(line.slice(0, cut)) > width) cut--
        out.push(line.slice(0, cut))
        line = line.slice(cut)
      }
    }
    out.push(line)
  }
  return out
}

