export const DEX: readonly DexEntry[] = ENTRIES.map((e, i) => ({ ...e, num: i + 1 }))

const BY_ID = new Map<SpeciesId, DexEntry>(DEX.map((d) => [d.id, d]))

export function dex(id: SpeciesId): DexEntry {
  const d = BY_ID.get(id)
  if (!d) throw new Error(`unknown species ${id}`)
  return d
}

/** The species this one evolved from, if any. */
export function preEvolution(id: SpeciesId): SpeciesId | null {
  for (const d of DEX) if (d.evolves?.into === id) return d.id
  return null
}
