import type { TypeId } from './types'

/**
 * The Beastiary: every species in the Azure Isles, in dex order. This file is
 * who each beast is — name, types, how it evolves, what it looks like and its
 * dex entry. Battle numbers (base stats, learnsets, catch rate) live in
 * src/data/species.ts; the art is drawn from `look` in src/art/creatures.
 *
 * Every creature here is an original design.
 */
export interface DexEntry {
  id: SpeciesId
  /** Dex number, 1-based, matching the order of DEX. */
  num: number
  /** Upper-case display name, ten characters at most. */
  name: string
  types: readonly [TypeId] | readonly [TypeId, TypeId]
  /** Level-up evolution, if any. */
  evolves?: { into: SpeciesId; level: number }
  /** One-line category, as in "LEAF PANGOLIN beast". */
  kind: string
  /** Metres and kilograms, for the entry page. */
  height: number
  weight: number
  /** The entry text: two or three short sentences. */
  entry: string
  /**
   * Art brief for the sprite: silhouette, pose, features and colours. The
   * front sprite faces left toward the player's side; the back sprite shows
   * the same beast from behind and a little above.
   */
  look: string
  /** Main colours, light to dark, for the art and for UI accents. */
  colors: readonly string[]
}

