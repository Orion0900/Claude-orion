// Generates src/face/canonical.ts from MediaPipe's canonical face model: the
// 468 mesh vertices (in centimetres, +z towards the viewer), its triangles,
// and the left/right mirror of every vertex, which the symmetry analysis and
// the tests are built on. Run: node scripts/gen-canonical.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const SOURCE =
  'https://raw.githubusercontent.com/google-ai-edge/mediapipe/master/mediapipe/modules/face_geometry/data/canonical_face_model.obj'
const cached = join(here, '.canonical_face_model.obj')

const obj = existsSync(cached) ? readFileSync(cached, 'utf8') : await (await fetch(SOURCE)).text()
if (!existsSync(cached)) writeFileSync(cached, obj)

const vertices = []
const triangles = []
for (const line of obj.split('\n')) {
  const parts = line.trim().split(/\s+/)
  if (parts[0] === 'v') vertices.push(parts.slice(1, 4).map(Number))
  if (parts[0] === 'f') triangles.push(...parts.slice(1, 4).map((p) => Number(p.split('/')[0]) - 1))
}
if (vertices.length !== 468) throw new Error(`expected 468 vertices, got ${vertices.length}`)

const mirror = vertices.map(([x, y, z], i) => {
  let best = i
  let bestD = Infinity
  vertices.forEach(([x2, y2, z2], j) => {
    const d = Math.hypot(-x - x2, y - y2, z - z2)
    if (d < bestD) {
      bestD = d
      best = j
    }
  })
  if (bestD > 1e-3) throw new Error(`vertex ${i} has no mirror (closest ${bestD})`)
  return best
})
mirror.forEach((j, i) => {
  if (mirror[j] !== i) throw new Error(`mirror is not an involution at ${i}`)
})

const round = (n) => Math.round(n * 1000) / 1000
const chunks = (arr, size) => Array.from({ length: Math.ceil(arr.length / size) }, (_, i) => arr.slice(i * size, i * size + size))
const out = `// Generated by scripts/gen-canonical.mjs — do not edit by hand.
//
// MediaPipe's canonical face model (Apache License 2.0, Google LLC):
// ${SOURCE}
// Vertex i is face-mesh landmark i. Units are centimetres; +x is the
// subject's left, +y up, +z towards the viewer.

/** The 468 canonical mesh vertices, flattened as x, y, z. */
export const CANONICAL_VERTICES: readonly number[] = [
${chunks(vertices.flat().map(round), 12).map((c) => '  ' + c.join(', ') + ',').join('\n')}
]

/** Mesh triangles as vertex-index triples, flattened. */
export const TRIANGLES: readonly number[] = [
${chunks(triangles, 24).map((c) => '  ' + c.join(', ') + ',').join('\n')}
]

/** MIRROR[i] is the landmark on the other side of the face from i (itself on the midline). */
export const MIRROR: readonly number[] = [
${chunks(mirror, 24).map((c) => '  ' + c.join(', ') + ',').join('\n')}
]
`
writeFileSync(join(here, '..', 'src', 'face', 'canonical.ts'), out)
console.log(`wrote canonical.ts: ${vertices.length} vertices, ${triangles.length / 3} triangles`)
